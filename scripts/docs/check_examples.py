#!/usr/bin/env python3
"""Verify Markdown Rust examples with Rustdoc (Python 3.11+, Cargo required).

Usage: python scripts/docs/check_examples.py [--check | --prepare-only]
Add --include-readmes to include the widget and terminal crate READMEs.
Only docs/widget/**/*.md and docs/terminal/**/*.md are selected by default.

Generated sources and a derived Cargo.lock live in target/docs-examples;
compiled artifacts reuse root target/ via --target-dir. Each preparation seeds
that lock from the workspace Cargo.lock, keeping its compatible dependency pins.
Cargo may add the verification package; external dependency drift fails the check.
The root lock/manifests are never written.
The first run may download pinned dependencies. No cleanup is performed, and the
platform/toolchain requirements of the real crates still apply.

Rustdoc decides which fences are Rust tests. Ordinary Rust tests execute;
OS/window/clipboard examples MUST be marked rust,no_run by their authors.
no_run compiles only, ignore is not validated, and non-Rust fences/prose are not
checked. This is not native-window, clipboard, rendering or docs-wide acceptance.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
EXTERNALS = ("wgpu", "winit", "anyhow", "pollster")
OWNER = "Generated by scripts/docs/check_examples.py\n"


def toml_value(value: object) -> str:
    """Serialize the dependency value types used by the workspace manifest."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(
            f"{toml_value(key)} = {toml_value(item)}" for key, item in value.items()
        ) + " }"
    raise ValueError(f"Unsupported workspace dependency value: {value!r}")


def rust_string(value: str) -> str:
    """An ordinary Rust string literal, including Windows paths and controls."""
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    return '"' + "".join(
        escapes.get(char, f"\\u{{{ord(char):x}}}" if ord(char) < 32 or ord(char) == 127 else char)
        for char in value
    ) + '"'


def markdown_files(root: Path, include_readmes: bool = False) -> list[Path]:
    files = [path for area in ("widget", "terminal")
             for path in (root / "docs" / area).rglob("*.md") if path.is_file()]
    if include_readmes:
        for crate in ("harbor-widget", "harbor-terminal"):
            readme = root / "crates" / crate / "README.md"
            if not readme.is_file():
                raise ValueError(f"Requested crate README is missing: {readme}")
            files.append(readme)
    if not files:
        raise ValueError("No Markdown selected in docs/widget or docs/terminal; refusing an empty check.")
    for path in files:
        if not path.resolve().is_relative_to(root):
            raise ValueError(f"Markdown resolves outside the repository: {path}")
    return sorted(files, key=lambda path: path.relative_to(root).as_posix())


def module_name(relative: Path) -> str:
    # Relative-path hashing is stable across ordering, checkout paths and names
    # that would collide after punctuation replacement. The prefix is Rust-safe.
    return "doc_" + hashlib.sha256(relative.as_posix().encode("utf-8")).hexdigest()


def library_source(root: Path, files: list[Path]) -> str:
    lines = ["// Generated; edit the Markdown sources, not this file."]
    for path in files:
        name = module_name(path.relative_to(root))
        lines.extend((f"#[doc = include_str!({rust_string(str(path.resolve()))})]", f"pub mod {name} {{}}"))
    return "\n".join(lines) + "\n"


def cargo_manifest(root: Path) -> str:
    workspace = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))
    dependencies = workspace["workspace"]["dependencies"]
    lines = ["# Generated; independent workspace and lockfile.", "[package]",
             'name = "harbor-doc-examples"', 'version = "0.0.0"',
             "edition = " + toml_value(workspace["package"]["edition"]),
             "publish = false", "", "[workspace]", "", "[dependencies]"]
    for name in ("harbor-widget", "harbor-terminal"):
        dependency = {"path": str((root / dependencies[name]["path"]).resolve())}
        if name == "harbor-widget":
            dependency["features"] = ["winit"]
        lines.append(f"{name} = {toml_value(dependency)}")
    for name in EXTERNALS:
        lines.append(f"{name} = {toml_value(dependencies[name])}")
    return "\n".join(lines) + "\n"


def prepare(root: Path, files: list[Path]) -> Path:
    """Write only our generated package; refuse to adopt foreign contents."""
    if not files:
        raise ValueError("No Markdown selected; refusing an empty check.")
    manifest_text, source = cargo_manifest(root), library_source(root, files)
    workspace_lock = (root / "Cargo.lock").read_bytes()
    package = root / "target" / "docs-examples"
    marker = package / ".check-examples-owned"
    lockfile = package / "Cargo.lock"
    manifest, library = package / "Cargo.toml", package / "src" / "lib.rs"
    for path in (package, marker, manifest, lockfile, library.parent, library):
        if path.is_symlink():
            raise ValueError(f"Refusing generated-package symlink: {path}")
    if package.exists() and any(package.iterdir()):
        if not marker.is_file() or marker.read_text(encoding="utf-8") != OWNER:
            raise ValueError(f"Refusing non-owned generated directory: {package}")
    library.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text(OWNER, encoding="utf-8")
    manifest.write_text(manifest_text, encoding="utf-8")
    library.write_text(source, encoding="utf-8")
    lockfile.write_bytes(workspace_lock)
    return manifest


def verify_external_pins(root: Path, derived_lock: Path) -> None:
    """Reject a successful example run that resolved outside workspace pins."""
    def external_packages(path: Path) -> set[tuple[str, str, str, str]]:
        lock = tomllib.loads(path.read_text(encoding="utf-8"))
        return {(item["name"], item["version"], item["source"], item.get("checksum", ""))
                for item in lock.get("package", []) if "source" in item}

    drift = external_packages(derived_lock) - external_packages(root / "Cargo.lock")
    if drift:
        names = ", ".join(f"{name} {version}" for name, version, _, _ in sorted(drift))
        raise ValueError(f"Example dependencies drifted outside workspace Cargo.lock: {names}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="execute Rustdoc tests (the default)")
    mode.add_argument("--prepare-only", action="store_true", help="generate the package without running Cargo")
    parser.add_argument("--include-readmes", action="store_true", help="also include both crate READMEs")
    args = parser.parse_args(argv)
    try:
        root = ROOT.resolve()
        files = markdown_files(root, args.include_readmes)
        manifest = prepare(root, files)
        print(f"Prepared {manifest} from {len(files)} Markdown files.", flush=True)
        print("Scope: Rust fences recognized by Rustdoc, not all documentation behavior.\n"
              "Runnable examples execute; OS/window/clipboard examples MUST use rust,no_run.\n"
              "no_run compiles only; ignored examples are not validated.", flush=True)
        if args.prepare_only:
            print("Prepare-only: Cargo was not run; examples have not been verified.")
            return 0
        command = ["cargo", "test", "--doc", "--manifest-path", str(manifest),
                   "--target-dir", str(root / "target")]
        print("Running: " + subprocess.list2cmdline(command), flush=True)
        result = subprocess.run(command, cwd=root, check=False)
        if result.returncode:
            print(f"Cargo/Rustdoc failed (exit {result.returncode}).", file=sys.stderr)
        else:
            verify_external_pins(root, manifest.with_name("Cargo.lock"))
        return result.returncode
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Example verification failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
